"""Street view data: captured spots -> master tiles -> the standard (SD) pack addons.

  build/points.json            every spot: where, its facing, its shots, its cube's numbers
  build/master/<id>/cube/      the spot's cube tiles at full (HD) resolution: the source for packs
  build/master/<id>/views/     single views of a spot not stitched yet
  build/packs/<name>/          the pack addons (packs.json: one per continent), SD tiles scaled
                               down from the master, each under the CurseForge budget

Pure helpers (tested in tests/test_tools.py) plus the import and build steps sv.py runs.
"""

